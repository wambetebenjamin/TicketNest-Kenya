export function getEventBySlug(slug: string): EventItem | undefined {
  return EVENTS.find((e) => e.slug === slug);
}

export function getSimilarEvents(slug: string, limit = 4): EventItem[] {
  const event = getEventBySlug(slug);
  if (!event) return [];
  const sameCategory = EVENTS.filter(
    (e) => e.slug !== slug && e.category === event.category && e.status === "live"
  );
  const sameCity = EVENTS.filter(
    (e) => e.slug !== slug && e.venue.city === event.venue.city && e.status === "live"
  );
  const merged = [...sameCategory, ...sameCity];
  return merged.slice(0, limit);
}
